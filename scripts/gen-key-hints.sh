#!/usr/bin/env bash
# Writes lib/key_hints.sh: the one-line hint of every setting, for the text
# menu. The English texts are the ones of the Settings screen of the panel
# (panel/web/modules/settings-model.js), so the menu, the panel and the
# reference say the same thing; the installed `dpistack` has no panel/
# directory, hence the generated copy in lib/.
#
#   scripts/gen-key-hints.sh            write lib/key_hints.sh
#   scripts/gen-key-hints.sh --check    exit 1 when it is out of date, or when
#                                       a key of the schema has no hint (the gate)
set -uo pipefail
REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# shellcheck source=lib/schema.sh
source "$REPO_DIR/lib/schema.sh"
OUT="$REPO_DIR/lib/key_hints.sh"

declare -A HINT=()
while IFS= read -r line; do
	HINT[${line%%|*}]="${line#*|}"
done < <(sed -n 's/^  \([A-Z][A-Z0-9_]*\): "\(.*\)",$/\1|\2/p' "$REPO_DIR/panel/web/modules/settings-model.js")

missing=0
for key in "${SCHEMA_KEYS[@]}"; do
	[[ "$key" == "METRICS_TOKEN" ]] && continue # generated, never edited in a menu
	if [[ -z "${HINT[$key]:-}" ]]; then
		echo "gen-key-hints: no hint for $key in panel/web/modules/settings-model.js" >&2
		missing=1
	fi
done
((missing == 0)) || exit 1

render() {
	cat <<'HEAD'
#!/usr/bin/env bash
# GENERATED by scripts/gen-key-hints.sh from the hints of the Settings screen
# (panel/web/modules/settings-model.js). Do not edit by hand.
# shellcheck disable=SC2034 # read by lib/menu.sh
declare -gA KEY_HINT=(
HEAD
	local key text
	for key in "${SCHEMA_KEYS[@]}"; do
		[[ -n "${HINT[$key]:-}" ]] || continue
		text="${HINT[$key]//\'/\'\\\'\'}"
		printf "\t[%s]='%s'\n" "$key" "$text"
	done
	echo ")"
}

if [[ "${1:-}" == "--check" ]]; then
	if ! render | cmp -s - "$OUT"; then
		echo "lib/key_hints.sh is out of date: run scripts/gen-key-hints.sh" >&2
		exit 1
	fi
	exit 0
fi
render >"$OUT"
