#!/usr/bin/env bash
# Builds dpistack-install.sh: install.sh, lib/, templates/, bin/ and
# tests/data/ in one file (tech.md slice 30). The logic is not rewritten:
# the file carries the files as heredocs, unpacks them into a temporary
# directory when it starts and runs the real install.sh from there, so the
# modular and the single-file installer are the same code.
#
#   scripts/bundle.sh [OUT]            write OUT (default dpistack-install.sh)
#   scripts/bundle.sh --check [OUT]    exit 1 when OUT is not what the current
#                                      sources would produce (the gate)
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
mode=build
if [[ "${1:-}" == "--check" ]]; then
	mode=check
	shift
fi
out="${1:-$root/dpistack-install.sh}"

# The heredoc terminator. A source file with this line in it would end its
# own heredoc early: the build refuses instead of producing a broken file.
DELIM="DPISTACK_BUNDLE_END"

cd "$root"

# Everything the installer needs from its own tree (the selfinstall payload
# of step_selfinstall.sh). The panel is not here: it is a Go source tree or
# a prebuilt binary that lies next to the file, as it does for install.sh.
files() {
	echo install.sh
	find lib templates bin tests/data -type f | LC_ALL=C sort
}

is_binary() {
	case "$1" in
	*.pcap) return 0 ;;
	*) return 1 ;;
	esac
}

generate() {
	cat <<'HEADER'
#!/usr/bin/env bash
# dpistack-install.sh: the dpistack installer in one file.
# Generated by scripts/bundle.sh from install.sh, lib/, templates/, bin/ and
# tests/data/; edit those and run scripts/bundle.sh, not this file.
#
# It unpacks the files into a temporary directory and runs install.sh from
# there with the same arguments. A ready panel binary (dpistack-panel-linux-
# amd64 or -arm64) or the panel/ directory is looked for next to this file.
set -uo pipefail

if [[ -f "${BASH_SOURCE[0]:-}" ]]; then
	DPISTACK_ORIGIN_DIR="$(cd -- "$(dirname -- "$(readlink -f -- "${BASH_SOURCE[0]}")")" &>/dev/null && pwd)"
else
	DPISTACK_ORIGIN_DIR="$PWD"
fi
export DPISTACK_ORIGIN_DIR

bundle_dir="$(mktemp -d)" || exit 1
trap 'rm -rf "$bundle_dir"' EXIT

# put <path> <mode>: the file's content comes on stdin
put() {
	mkdir -p "$(dirname "$bundle_dir/$1")"
	cat >"$bundle_dir/$1"
	chmod "$2" "$bundle_dir/$1"
}

# put_b64 <path> <mode>: the same for a binary file, in base64
put_b64() {
	mkdir -p "$(dirname "$bundle_dir/$1")"
	base64 -d >"$bundle_dir/$1"
	chmod "$2" "$bundle_dir/$1"
}

HEADER
	local f perm
	while IFS= read -r f; do
		perm=$(stat -c %a "$f")
		if is_binary "$f"; then
			printf 'put_b64 %s %s <<'"'"'%s'"'"'\n' "$f" "$perm" "$DELIM"
			base64 "$f"
		else
			if LC_ALL=C grep -q "^${DELIM}\$" "$f"; then
				echo "bundle: $f contains the heredoc terminator $DELIM" >&2
				return 1
			fi
			if [[ -n "$(tail -c1 "$f")" ]]; then
				echo "bundle: $f has no newline at the end, a heredoc would add one" >&2
				return 1
			fi
			if [[ "$(wc -c <"$f")" != "$(tr -d '\0' <"$f" | wc -c)" ]]; then
				echo "bundle: $f has NUL bytes, add it to is_binary" >&2
				return 1
			fi
			printf 'put %s %s <<'"'"'%s'"'"'\n' "$f" "$perm" "$DELIM"
			cat "$f"
		fi
		echo "$DELIM"
	done < <(files)
	cat <<'FOOTER'

bash "$bundle_dir/install.sh" "$@"
exit $?
FOOTER
}

if [[ "$mode" == "check" ]]; then
	tmp="$(mktemp)"
	trap 'rm -f "$tmp"' EXIT
	generate >"$tmp"
	if [[ ! -f "$out" ]]; then
		echo "bundle: $out does not exist; run scripts/bundle.sh" >&2
		exit 1
	fi
	if ! cmp -s "$tmp" "$out"; then
		echo "bundle: $out is out of date with the sources; run scripts/bundle.sh" >&2
		exit 1
	fi
	echo "bundle: $out matches the sources"
	exit 0
fi

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT
generate >"$tmp"
install -m 0755 "$tmp" "$out"
echo "bundle: wrote $out ($(wc -c <"$out") bytes, $(files | wc -l) files)"
